def cupl_pins(name):
    """{pin: signal} from the PIN lines of a CUPL source."""
    text = re.sub(r'/\*.*?\*/', ' ', (PLD / name).read_text(), flags=re.S)
    return {int(n): s for n, s in re.findall(r'^\s*PIN\s+(\d+)\s*=\s*(\w+)\s*;', text, flags=re.M)}


def load_base():
    blob = subprocess.run(['git', 'show', f'{BASE}:design/kicad/rosco_m68k.kicad_pcb'], cwd=KICAD,
                          capture_output=True, check=True).stdout
    tmp = Path(tempfile.mkdtemp()) / 'base.kicad_pcb'
    tmp.write_bytes(blob)
    # the design rules and net classes live in the project file, not in the board
    tmp.with_suffix('.kicad_pro').write_bytes(BOARD.with_suffix('.kicad_pro').read_bytes())
    return pcb.LoadBoard(str(tmp))


def save(b):
    """SaveBoard also rewrites the .kicad_pro and .kicad_prl next to the board from whatever
    settings the loaded board carries. Those files belong to the designer (the DRC rules live
    in the .kicad_pro), so they are put back exactly as they were."""
    keep = {p: p.read_bytes() for p in (BOARD.with_suffix('.kicad_pro'), BOARD.with_suffix('.kicad_prl')) if p.exists()}
    pcb.SaveBoard(str(BOARD), b)
    for p, data in keep.items():
        p.write_bytes(data)


