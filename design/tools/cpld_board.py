"""Turn the r2.13 THT board into r2.14: two ATF1502AS-10JU44 instead of four ATF22V10C.

r2.13 was drawn by hand and is not generated by anything, so this script does not rebuild the
board -- it edits it, always starting again from the r2.13 file in git (BASE), so running it twice
gives the same result:

  1. removes the GALs IC2, IC3, IC5 and IC6 and their silkscreen names, but keeps the copper that
     led to them: its loose ends are what the router connects the new pins to;
  2. places both CPLDs in PLCC-44 through-hole sockets, like the DUART IC4, one above the other
     where the three glue GALs stood, with room between them for a PLCC extractor. A socket is
     24.6 mm across and the old IC2 sat in a 24.4 mm gap between the CPU and the ROMs, so it
     cannot go back there. J8, R31, R32 and R16 move left, onto the small logo (removed with its
     "Classic version 2" text); the GAL decoupling C23-C25 and the DUART's C27/C28 line up in one
     column under J9;
  3. adds the JTAG header J9 (the ATF150x is programmed in circuit) and C33, IC2's second 100 nF;
  4. takes the nets of the new parts from the schematic's netlist, not from its own idea of it;
  5. tears up whatever track or via the new copper collides with and cuts the old stubs back;
  6. takes every supply pin of the sockets to its plane through a via of its own.

Step 6 is needed although the sockets are through-hole: the planes keep 0.508 mm from other
nets, and between the socket pins on their 2.54 mm grid that leaves no copper at all, so the
inner-ring supply pins sit in holes of the plane. Each gets a short track to a via beside the
socket, outside the ring of pins (inside it the plane is an island), and a solid connection
instead of thermal spokes; the few with no straight way out are left to cpld_route.py. What is left
unconnected is routed by cpld_route.py with KiCadRoutingTools.

    "C:/Program Files/KiCad/10.0/bin/python.exe" design/tools/cpld_board.py [--suggest]

--suggest prints, for each CPLD, the pin assignment that puts every signal on the pin nearest
to where its net already runs; that is how the PIN lines in code/pld/cpld/*.pld were chosen.
"""
