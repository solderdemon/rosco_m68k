def find(b, ref):
    hits = [fp for fp in b.GetFootprints() if fp.GetReference() == ref]
    assert len(hits) <= 1, ref
    return hits[0] if hits else None


def footprint(ref, fpid, value):
    lib, name = fpid.split(':')
    path = FPLIB / f'{lib}.pretty' if lib != 'rosco_m68k' else KICAD / 'rosco_m68k.pretty'
    fp = pcb.FootprintLoad(str(path), name)
    fp.SetFPID(pcb.LIB_ID(lib, name))
    fp.SetReference(ref)
    fp.SetValue(value)
    return fp


def at_mm(x, y):
    return pcb.VECTOR2I(mm(x), mm(y))


# ---- step 1: silkscreen ----------------------------------------------------------------------
def silkscreen(b):
    for fp in list(b.GetFootprints()):
        p = fp.GetPosition()
        if fp.GetReference() == 'REF**' and abs(pcb.ToMM(p.x) - JUNK_LOGO[0]) < 0.5 and abs(pcb.ToMM(p.y) - JUNK_LOGO[1]) < 0.5:
            remove(b, fp)
    for d in list(b.GetDrawings()):
        if isinstance(d, pcb.PCB_TEXT):
            if d.GetText() in JUNK_TEXT:
                remove(b, d)
            elif d.GetText() in REVISION_TEXT:
                d.SetText(REVISION_TEXT[d.GetText()])
    left = {d.GetText() for d in b.GetDrawings() if isinstance(d, pcb.PCB_TEXT)}
    assert not JUNK_TEXT & left, JUNK_TEXT & left
    tb = b.GetTitleBlock()
    tb.SetRevision('2.14-DEV')
    tb.SetDate('2026-09-27')


# ---- track surgery ---------------------------------------------------------------------------
def zone_holds(b, net, layer, pt):
    return any(z.GetNetname() == net and z.IsOnLayer(layer) and z.HitTestFilledArea(layer, pt)
               for z in b.Zones() if not z.GetIsRuleArea())


def prune(b, nets, region=None):
    """Remove every track and via of `nets` that dangles, until none does. With `region`
    (a BOX2I) only copper whose loose end lies inside it goes, so a stub is cut back to the
    edge of the region and no further."""
    removed = 0
    while True:
        by_net = {}
        for t in b.GetTracks():
            if t.GetNetname() in nets:
                by_net.setdefault(t.GetNetname(), []).append(t)
        pads = {}
        for fp in b.GetFootprints():
            for p in fp.Pads():
                if p.GetNetname() in nets:
                    pads.setdefault(p.GetNetname(), []).append(p)
        dead = []
        for net, items in by_net.items():
            vias = [t for t in items if t.Type() == pcb.PCB_VIA_T]
            segs = [t for t in items if t.Type() == pcb.PCB_TRACE_T]
            for v in vias:
                r = v.GetWidth(pcb.F_Cu) // 2
                links = sum(1 for s in segs for e in (s.GetStart(), s.GetEnd()) if (e - v.GetPosition()).EuclideanNorm() <= r)
                links += sum(1 for p in pads.get(net, []) if p.HitTest(v.GetPosition()))
                if links < 2 and not any(zone_holds(b, net, l, v.GetPosition()) for l in v.GetLayerSet().CuStack()) \
                        and (region is None or region.Contains(v.GetPosition())):
                    dead.append(v)
            for s in segs:
                layer = s.GetLayer()
                for e in (s.GetStart(), s.GetEnd()):
                    ok = any(p.IsOnLayer(layer) and p.HitTest(e) for p in pads.get(net, []))
                    ok = ok or any((v.GetPosition() - e).EuclideanNorm() <= v.GetWidth(pcb.F_Cu) // 2 for v in vias)
                    ok = ok or any(o is not s and o.GetLayer() == layer and o.HitTest(e, 0) for o in segs)
                    ok = ok or zone_holds(b, net, layer, e)
                    ok = ok or (region is not None and not region.Contains(e))
                    if not ok:
                        dead.append(s)
                        break
        dead = {t.m_Uuid.AsString(): t for t in dead}
        if not dead:
            return removed
        for t in dead.values():
            remove(b, t)
        removed += len(dead)


def rip_collisions(b, footprints):
    """Remove every track and via that the pads of `footprints` would short or crowd."""
    hit = []
    pads = [p for fp in footprints for p in fp.Pads()]
    for t in b.GetTracks():
        layers = [t.GetLayer()] if t.Type() == pcb.PCB_TRACE_T else list(t.GetLayerSet().CuStack())
        for p in pads:
            # a track of the pad's own net may touch it; a via may not, its hole needs room
            if t.Type() == pcb.PCB_TRACE_T and p.GetNetname() and p.GetNetname() == t.GetNetname():
                continue
            common = [l for l in layers if p.IsOnLayer(l)]
            if any(t.GetEffectiveShape(l).Collide(p.GetEffectiveShape(l), CLEARANCE) for l in common):
                hit.append(t)
                break
    nets = {t.GetNetname() for t in hit}
    for t in hit:
        remove(b, t)
    return nets, len(hit)


