def place_centred(fp, x, y):
    """Put a footprint so that its courtyard is centred on (x, y)."""
    fp.SetPosition(at_mm(0, 0))
    c = fp.GetCourtyard(pcb.F_CrtYd).BBox().GetCenter()
    fp.SetPosition(at_mm(x, y) - c)


def place_chip(b, ref):
    pld, (x, y), label = CHIPS[ref]
    fp = footprint(ref, SOCKET, 'ATF1502AS-10JU44')
    b.Add(fp)
    place_centred(fp, x, y)
    # inside the inner ring of pins, which leaves about 9 mm
    fp.Reference().SetPosition(at_mm(x, y - 2.2))
    fp.Reference().SetLayer(pcb.F_SilkS)
    fp.Value().SetVisible(False)
    t = pcb.PCB_TEXT(b)
    t.SetText(label)
    t.SetPosition(at_mm(x, y + 0.9))
    t.SetLayer(pcb.F_SilkS)
    t.SetTextSize(pcb.VECTOR2I(mm(0.9), mm(0.9)))
    t.SetTextThickness(mm(0.15))
    b.Add(t)
    return fp


