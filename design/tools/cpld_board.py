# ---- nets ------------------------------------------------------------------------------------
def netlist():
    """{(ref, pin): (net, pinfunction, pintype), ...} and {ref: sheet path} from the schematic."""
    out = Path(tempfile.mkdtemp()) / 'solderdemon_m68k.xml'
    subprocess.run([CLI, 'sch', 'export', 'netlist', '--format', 'kicadxml', '-o', str(out), str(SCH)],
                   check=True, capture_output=True)
    root = ET.parse(out).getroot()
    pins = {}
    for net in root.iter('net'):
        for node in net.iter('node'):
            pins[(node.get('ref'), node.get('pin'))] = (net.get('name'), node.get('pinfunction') or '',
                                                       node.get('pintype') or '')
    comps = {}
    for c in root.iter('comp'):
        sp = c.find('sheetpath')
        comps[c.get('ref')] = (sp.get('tstamps') + c.find('tstamps').text, sp.get('names'),
                               c.find('value').text, c.find('footprint').text)
    return pins, comps


def apply_nets(b, footprints, pins, comps):
    for fp in footprints:
        ref = fp.GetReference()
        path, sheet, value, fpid = comps[ref]
        assert fpid == fp.GetFPIDAsString(), (ref, fpid, fp.GetFPIDAsString())
        fp.SetPath(pcb.KIID_PATH(path))
        fp.SetValue(value)
        if hasattr(fp, 'SetSheetname'):
            fp.SetSheetname(sheet.strip('/').split('/')[-1] if sheet != '/' else '')
        for p in fp.Pads():
            net, func, kind = pins.get((ref, p.GetNumber()), ('', '', ''))
            if not net:
                p.SetNetCode(0)
                continue
            net = net.replace('/', '{slash}')       # how the board spells '/' in a net name
            ni = b.FindNet(net)
            if ni is None:
                ni = pcb.NETINFO_ITEM(b, net)
                b.Add(ni)
            p.SetNet(ni)
            p.SetPinFunction(func)
            p.SetPinType(kind)


def check_all_nets(b, pins):
    """Every pad on the board has the net the schematic gives it."""
    bad = []
    for fp in b.GetFootprints():
        for p in fp.Pads():
            key = (fp.GetReference(), p.GetNumber())
            want = pins.get(key, ('',))[0]
            if key in pins and not want.startswith('unconnected-') and want != p.GetNetname().replace('{slash}', '/'):
                bad.append((key, p.GetNetname(), want))
    assert not bad, bad[:20]


# ---- --suggest -------------------------------------------------------------------------------
def hungarian(cost):
    """Minimum-cost assignment of rows to columns (rows <= columns). Returns {row: col}."""
    n, m = len(cost), len(cost[0])
    INF = float('inf')
    u, v, p, way = [0.0] * (n + 1), [0.0] * (m + 1), [0] * (m + 1), [0] * (m + 1)
    for i in range(1, n + 1):
        p[0], j0 = i, 0
        minv, used = [INF] * (m + 1), [False] * (m + 1)
        while True:
            used[j0] = True
            i0, delta, j1 = p[j0], INF, 0
            for j in range(1, m + 1):
                if not used[j]:
                    cur = cost[i0 - 1][j - 1] - u[i0] - v[j]
                    if cur < minv[j]:
                        minv[j], way[j] = cur, j0
                    if minv[j] < delta:
                        delta, j1 = minv[j], j
            for j in range(m + 1):
                if used[j]:
                    u[p[j]] += delta; v[j] -= delta
                else:
                    minv[j] -= delta
            j0 = j1
            if p[j0] == 0:
                break
        while True:
            j1 = way[j0]; p[j0] = p[j1]; j0 = j1
            if j0 == 0:
                break
    return {p[j] - 1: j - 1 for j in range(1, m + 1) if p[j]}


OUTPUTS = {'EVENRAMSEL', 'ODDRAMSEL', 'EVENROMSEL', 'ODDROMSEL', 'IOSEL', 'EXPSEL', 'DTACK', 'WR',
           'DUASEL', 'DUAIACK', 'HALT', 'RESET', 'RUNLED', 'BERR'}


def suggest(b, chips):
    """Put each signal on the free pin closest to the nearest copper its net already has."""
    for fp in chips:
        ref = fp.GetReference()
        pins = cupl_pins(CHIPS[ref][0])
        driven = OUTPUTS if ref == 'IC3' else OUTPUTS - {'HALT', 'RESET'}
        pads = {int(p.GetNumber()): p.GetPosition() for p in fp.Pads()}
        fixed = {n: s for n, s in pins.items() if n == CLOCK_PIN}
        sigs = [s for n, s in sorted(pins.items()) if n not in fixed]
        slots = [n for n in pads if n not in VCC_PINS + GND_PINS and n not in JTAG_PINS and n not in fixed]
        others = [f for f in b.GetFootprints() if f.GetReference() not in CHIPS]
        cost = []
        for s in sigs:
            pts = [p.GetPosition() for f in others for p in f.Pads() if p.GetNetname() == s]
            pts += [e for t in b.GetTracks() if t.GetNetname() == s
                    for e in ((t.GetPosition(),) if t.Type() == pcb.PCB_VIA_T else (t.GetStart(), t.GetEnd()))]
            assert pts, f'{s} has no copper on the board'
            row = []
            for n in slots:
                if n in DEDICATED_INPUTS and s in driven:
                    row.append(1e9); continue
                row.append(min((pads[n] - q).EuclideanNorm() for q in pts) / 1e6)
            cost.append(row)
        best = hungarian(cost)
        print(f'/* {ref}: suggested pins */')
        for n, s in sorted({**fixed, **{slots[best[i]]: s for i, s in enumerate(sigs)}}.items()):
            print(f'PIN {n:<2} = {s};')


def plane_vias(b, footprints):
    """Connect every VCC/GND pad of `footprints` to its plane with a short track to a via, the
    via as close to the pad as the copper around allows, away from the middle of the part first:
    the ring of socket pins cuts the plane inside it off from the rest. A pad with no straight
    way out is returned, for cpld_route.py to connect with KiCadRoutingTools' repair_planes."""
    via_d, drill, width, gap, hole_gap = mm(0.6), mm(0.3), mm(0.3), mm(0.2), mm(0.3)
    added, left = 0, []
    for fp in footprints:
        centre = fp.GetCourtyard(pcb.F_CrtYd).BBox().GetCenter()
        # the via has to land outside the ring of pins, clear of the outermost pads
        ring = max(max(abs(q.GetPosition().x - centre.x), abs(q.GetPosition().y - centre.y)) for q in fp.Pads())
        ring += max(q.GetSize(pcb.F_Cu).x for q in fp.Pads()) // 2 + via_d // 2 + gap
        for pad in fp.Pads():
            net = pad.GetNetname()
            if net not in ('VCC', 'GND'):
                continue
            pad.SetLocalZoneConnection(pcb.ZONE_CONNECTION_FULL)
            p = pad.GetPosition()
            outward = math.atan2(p.y - centre.y, p.x - centre.x)
            area = pcb.BOX2I(p - pcb.VECTOR2I(mm(5), mm(5)), pcb.VECTOR2L(mm(10), mm(10)))
            near = [o for o in list(b.GetTracks()) + [q for f in b.GetFootprints() for q in f.Pads()]
                    if o is not pad and o.GetBoundingBox().Intersects(area)]
            holes = [o for o in near if (o.Type() == pcb.PCB_VIA_T or
                                         (o.Type() == pcb.PCB_PAD_T and o.GetDrillSize().x > 0))]
            done = False
            tries = [(dist, k, layer) for dist in (1.8, 2.2, 2.6, 3.0, 3.5, 4.0, 4.5, 5.0, 5.5, 6.0)
                     for layer in (pcb.B_Cu, pcb.F_Cu)
                     for k in sorted(range(-36, 36), key=abs)]
            for dist, k, layer in tries:
                    a = outward + k * math.pi / 36
                    at = p + pcb.VECTOR2I(int(mm(dist) * math.cos(a)), int(mm(dist) * math.sin(a)))
                    if max(abs(at.x - centre.x), abs(at.y - centre.y)) < ring:
                        continue
                    v = pcb.PCB_VIA(b)
                    v.SetPosition(at); v.SetWidth(via_d); v.SetDrill(drill)
                    v.SetLayerPair(pcb.F_Cu, pcb.B_Cu); v.SetNet(pad.GetNet())
                    t = pcb.PCB_TRACK(b)
                    t.SetStart(p); t.SetEnd(at); t.SetWidth(width); t.SetLayer(layer); t.SetNet(pad.GetNet())
                    clash = False
                    for o in near:
                        if o.GetNetname() == net:
                            continue
                        for l in (pcb.F_Cu, pcb.B_Cu):
                            if not o.IsOnLayer(l):
                                continue
                            os_ = o.GetEffectiveShape(l)
                            if v.GetEffectiveShape(l).Collide(os_, gap) or                                     (l == layer and t.GetEffectiveShape(l).Collide(os_, gap)):
                                clash = True
                                break
                        if clash:
                            break
                    for o in holes:                      # holes of any net, this pad's own too
                        r = (o.GetDrillSize().x if o.Type() == pcb.PCB_PAD_T else o.GetDrill()) // 2
                        if (o.GetPosition() - at).EuclideanNorm() < r + drill // 2 + hole_gap:
                            clash = True
                    if (pad.GetPosition() - at).EuclideanNorm() < pad.GetDrillSize().x // 2 + drill // 2 + hole_gap:
                        clash = True
                    if not clash:
                        b.Add(v); b.Add(t)
                        added += 1
                        done = True
                        break
            if not done:
                left.append(f'{fp.GetReference()}.{pad.GetNumber()}')
    return added, left


def drc(extra=()):
    save_path = BOARD
    rpt = Path(tempfile.mkdtemp()) / 'drc.json'
    subprocess.run([CLI, 'pcb', 'drc', '--format', 'json', *extra, '-o', str(rpt), str(save_path)], capture_output=True)
    return json.loads(rpt.read_text(encoding='utf-8'))


def main():
    b = load_base()
    silkscreen(b)
    gal_nets = {p.GetNetname() for r in OLD_GALS for p in find(b, r).Pads()} - {'', 'GND', 'VCC'}
    for r in OLD_GALS:
        remove(b, find(b, r))
    # Nets that lived purely between the GALs (BOOT, ANYIACK) are internal to IC2 now: their
    # copper goes. The rest stays, its loose ends are where the new pins get connected.
    padded = {p.GetNetname() for fp in b.GetFootprints() for p in fp.Pads()}
    orphans = [t for t in b.GetTracks() if t.GetNetname() in gal_nets - padded]
    for t in orphans:
        remove(b, t)
    print('tracks of nets that only ran between the GALs:', len(orphans), sorted(gal_nets - padded))
    moved = move_parts(b)
    tidy_refs(b)
    chips = [place_chip(b, r) for r in CHIPS]
    if '--suggest' in sys.argv:
        return suggest(b, chips)
    caps = place_caps(b)
    tidy_refs(b)
    jtag = place_jtag(b)
    new = chips + caps + [jtag]
    pins, comps = netlist()
    apply_nets(b, new, pins, comps)
    check_all_nets(b, pins)
    nets, n = rip_collisions(b, new + moved)
    print(f'tracks and vias in the way of the new and moved parts: {n} on {len(nets)} nets')
    # cut the loose ends left by the GAL pins and by the rip-up back to the edge of the sockets
    cut = 0
    for fp in chips:
        box = fp.GetCourtyard(pcb.F_CrtYd).BBox()
        box.Inflate(mm(0.5))
        cut += prune(b, (gal_nets | nets) - {'GND', 'VCC'}, region=box)
    print('old stubs cut back to the edge of the sockets:', cut)
    n, left = plane_vias(b, chips)
    print('socket supply pins taken to the planes:', n, '; left to repair_planes:', left)
    pcb.ZONE_FILLER(b).Fill(b.Zones())
    save(b)
    b.BuildConnectivity()
    print('unconnected before routing:', b.GetConnectivity().GetUnconnectedCount(True))


if __name__ == '__main__':
    main()
